  function isNetworkFail(err) {
    if (!err) return true;
    var m = String(err.message || err);
    if (m === "Failed to fetch" || m === "NetworkError" || m === "network") return true;
    if (err.name === "TypeError") return true;
    return false;
  }

  function postPlanOnce(body) {
    return fetch("/plan", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(body)
    }).then(function (res) {
      return res.text().then(function (text) {
        var json = null;
        var parseErr = null;
        try { json = JSON.parse(text); } catch (e) { parseErr = e; }
        return { res: res, json: json, parseErr: parseErr, text: text };
      });
    });
  }

  function postPlan(body, attempt) {
    return postPlanOnce(body).then(function (got) {
      if (got.parseErr) {
        if (attempt < 1) return postPlan(body, attempt + 1);
        throw new Error("proxy returned non-JSON");
      }
      var json = got.json;
      if (!got.res.ok) {
        var msg = (json && json.error) ? String(json.error) : ("proxy HTTP " + got.res.status);
        var err = new Error(msg);
        err.status = got.res.status;
        err.noRetry = got.res.status === 422 || got.res.status === 400 || got.res.status === 503;
        throw err;
      }
      return json;
    }).catch(function (err) {
      if (err && err.noRetry) throw err;
      if (attempt < 1 && isNetworkFail(err)) return postPlan(body, attempt + 1);
      if (attempt < 1 && err && /non-JSON/.test(String(err.message))) return postPlan(body, attempt + 1);
      throw err;
    });
  }

