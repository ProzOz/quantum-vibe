  function localPercents(sim) {
    var out = {};
    var counts = (sim && sim.counts) || {};
    var shots = (sim && sim.shots) || 0;
    var tot = shots;
    if (!tot) {
      Object.keys(counts).forEach(function (k) { tot += counts[k] || 0; });
    }
    if (!tot) tot = 1;
    Object.keys(counts).forEach(function (k) {
      out[k] = ((counts[k] || 0) / tot) * 100;
    });
    return out;
  }

  function hwPercents(wk) {
    if (wk && wk.percents && typeof wk.percents === "object") return wk.percents;
    var counts = (wk && wk.counts) || {};
    var shots = (wk && wk.shots) || 0;
    var tot = shots;
    if (!tot) {
      Object.keys(counts).forEach(function (k) { tot += counts[k] || 0; });
    }
    if (!tot) tot = 1;
    var out = {};
    Object.keys(counts).forEach(function (k) {
      out[k] = ((counts[k] || 0) / tot) * 100;
    });
    return out;
  }

  function dominantLocalKeys(sim) {
    var counts = (sim && sim.counts) || {};
    var keys = Object.keys(counts).filter(function (k) { return (counts[k] || 0) > 0; });
    keys.sort(function (a, b) { return (counts[b] || 0) - (counts[a] || 0); });
    if (keys.length > 2) keys = keys.slice(0, 2);
    return keys;
  }

  function wukongCompareLine(sim, wk) {
    var loc = localPercents(sim);
    var hw = hwPercents(wk);
    var keys = dominantLocalKeys(sim);
    if (!keys.length) keys = Object.keys((wk && wk.counts) || {}).slice(0, 2);
    var localBits = keys.map(function (k) {
      return "|" + k + "|≈" + fmtPct(loc[k] || 0) + "%";
    }).join(" ");
    var hwBits = keys.map(function (k) {
      return "|" + k + "|≈" + fmtPct(hw[k] || 0) + "%";
    }).join(" ");
    if (state.lang === "th") {
      return "เครื่องเงียบ " + localBits + " · ชิปจริงเอียงและมี noise (" + hwBits + ") — ของเล่นสอน ไม่ใช่ quantum advantage";
    }
    return "Quiet machine " + localBits + " · real chip is biased and noisy (" + hwBits + ") — a teaching toy, not quantum advantage";
  }

