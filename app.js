  function parseOriginResult(raw, nQubits, shotsHint) {
    try {
      var n = parseInt(nQubits, 10);
      if (!isFinite(n) || n < 1) n = 2;
      var shots = parseInt(shotsHint, 10);
      if (!isFinite(shots) || shots < 1) shots = 256;

      function coerce(raw0) {
        if (raw0 == null) return null;
        if (typeof raw0 === "string") return parsePreview(raw0);
        if (typeof raw0 === "object") return raw0;
        return null;
      }

      function parsePreview(s) {
        var t = String(s || "").trim();
        if (!t) return null;
        try { return JSON.parse(t); } catch (e) {}
        var start0 = t.indexOf("{");
        var end0 = t.lastIndexOf("}");
        if (start0 >= 0 && end0 > start0) {
          var chunk = t.slice(start0, end0 + 1);
          try { return JSON.parse(chunk); } catch (e2) {}
          try { return JSON.parse(chunk.replace(/'/g, '"')); } catch (e3) {}
        }
        var keyM = t.match(/\bkey\s*[:=]\s*(\[[^[\]]*\])/i);
        var valM = t.match(/\bvalue\s*[:=]\s*(\[[^[\]]*\])/i);
        if (keyM && valM) {
          try {
            return {
              key: JSON.parse(keyM[1].replace(/'/g, '"')),
              value: JSON.parse(valM[1].replace(/'/g, '"'))
            };
          } catch (e4) {}
        }
        return null;
      }

      function asNum(v) {
        if (typeof v === "boolean") return null;
        if (typeof v === "number") return isFinite(v) ? v : null;
        if (typeof v === "string" && v.trim() !== "") {
          var x = Number(v);
          return isFinite(x) ? x : null;
        }
        return null;
      }

      function toBits(label, width) {
        var s = String(label == null ? "" : label).trim().replace(/\s+/g, "");
        s = s.replace(/[|⟩><⟨]/g, "");
        if (!s) return null;
        var bits = null;
        if (/^0x[0-9a-fA-F]+$/i.test(s)) bits = parseInt(s, 16).toString(2);
        else if (/^[01]+$/.test(s)) bits = s;
        else if (/^\d+$/.test(s)) bits = parseInt(s, 10).toString(2);
        else return null;
        var w = width && width > 0 ? width : 2;
        while (bits.length < w) bits = "0" + bits;
        if (bits.length > w) bits = bits.slice(-w);
        return bits;
      }

      function looksLabel(k) {
        var s = String(k == null ? "" : k).trim().replace(/\s+/g, "");
        if (!s) return false;
        return /^[01]+$/.test(s) || /^0x[0-9a-fA-F]+$/i.test(s) || /^\d+$/.test(s);
      }

      function fromKeyValue(keys, vals, width) {
        if (!keys || !vals || typeof keys.length !== "number" || typeof vals.length !== "number") return null;
        if (keys.length !== vals.length || !keys.length) return null;
        var out = [];
        for (var i = 0; i < keys.length; i++) {
          var bits = toBits(keys[i], width);
          var num = asNum(vals[i]);
          if (bits == null || num == null) continue;
          out.push([bits, num]);
        }
        return out.length ? out : null;
      }

      function fromLabeled(obj, width) {
        if (!obj || typeof obj !== "object" || Array.isArray(obj)) return null;
        var keys = Object.keys(obj);
        if (!keys.length) return null;
        for (var i = 0; i < keys.length; i++) {
          if (!looksLabel(keys[i])) return null;
        }
        var out = [];
        for (var j = 0; j < keys.length; j++) {
          var bits = toBits(keys[j], width);
          var num = asNum(obj[keys[j]]);
          if (bits == null || num == null) continue;
          out.push([bits, num]);
        }
        return out.length ? out : null;
      }

      function walk(obj, width, depth) {
        if (depth > 8 || obj == null) return null;
        if (typeof obj === "string") {
          if (obj.indexOf("Status:") === 0) return null;
          var parsed = parsePreview(obj);
          if (parsed != null && parsed !== obj) return walk(parsed, width, depth + 1);
          return null;
        }
        if (Array.isArray(obj)) {
          if (obj.length && obj.every(function (x) {
            return x && typeof x === "object" && !Array.isArray(x) && ("key" in x) && ("value" in x);
          })) {
            var scalarKeys = obj.every(function (x) { return !Array.isArray(x.key); });
            if (scalarKeys) {
              var gotList = fromKeyValue(
                obj.map(function (x) { return x.key; }),
                obj.map(function (x) { return x.value; }),
                width
              );
              if (gotList) return gotList;
            }
          }
          for (var a = 0; a < obj.length; a++) {
            var gotA = walk(obj[a], width, depth + 1);
            if (gotA) return gotA;
          }
          return null;
        }
        if (typeof obj === "object") {
          var gotKv = fromKeyValue(obj.key, obj.value, width);
          if (gotKv) return gotKv;
          if (obj.counts != null) {
            var gotC = walk(obj.counts, width, depth + 1);
            if (gotC) return gotC;
          }
          var labeled = fromLabeled(obj, width);
          if (labeled) return labeled;
          var nests = ["results", "data", "result"];
          for (var ni = 0; ni < nests.length; ni++) {
            if (obj[nests[ni]] != null) {
              var gotN = walk(obj[nests[ni]], width, depth + 1);
              if (gotN) return gotN;
            }
          }
          var ks = Object.keys(obj);
          for (var k = 0; k < ks.length; k++) {
            var gotV = walk(obj[ks[k]], width, depth + 1);
            if (gotV) return gotV;
          }
        }
        return null;
      }

      var obj = coerce(raw);
      if (obj == null) return null;
      var pairs = walk(obj, n, 0);
      if (!pairs || !pairs.length) return null;
      var merged = {};
      for (var i = 0; i < pairs.length; i++) {
        merged[pairs[i][0]] = (merged[pairs[i][0]] || 0) + pairs[i][1];
      }
      var keys = Object.keys(merged);
      if (!keys.length) return null;
      var allProb = true;
      var total = 0;
      for (var j = 0; j < keys.length; j++) {
        total += merged[keys[j]];
        if (merged[keys[j]] > 1.01) allProb = false;
      }
      var counts = {};
      var percents = {};
      if (allProb && Math.abs(total - 1) <= 0.08) {
        for (var p = 0; p < keys.length; p++) {
          percents[keys[p]] = merged[keys[p]] * 100;
          counts[keys[p]] = Math.round(merged[keys[p]] * shots);
        }
        return { counts: counts, percents: percents, shots: shots, n: n };
      }
      var shotSum = 0;
      for (var c = 0; c < keys.length; c++) {
        counts[keys[c]] = Math.round(merged[keys[c]]);
        shotSum += counts[keys[c]];
      }
      if (shotSum <= 0) return null;
      for (var d = 0; d < keys.length; d++) {
        percents[keys[d]] = (counts[keys[d]] / shotSum) * 100;
      }
      return { counts: counts, percents: percents, shots: shotSum, n: n };
    } catch (e) {
      return null;
    }
  }

