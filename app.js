  function parseNamedQubits(text, n) {
    var names = [];
    var i;
    for (i = 0; i < n; i++) names[i] = "";
    var s = String(text || "");
    if (!s) return null;
    var re = /(?:q(?:ubit)?|ควิบิต)\s*(\d+)\s*(?:คือ|=|:|–|—|-)\s*([^,;\/\n|]+)/gi;
    var m;
    var filled = 0;
    while ((m = re.exec(s))) {
      var idx = parseInt(m[1], 10);
      if (idx >= 0 && idx < n) {
        var nm = cleanQubitName(m[2]);
        if (nm && !names[idx]) {
          names[idx] = nm;
          filled++;
        }
      }
    }
    if (filled === n) return names;
    var parts = s.split(/\s*(?:\/|,|;|\||และ|กับ|&|\+|vs\.?|versus|and)\s*/i).map(function (x) {
      return cleanQubitName(x.replace(/^(?:q(?:ubit)?|ควิบิต)\s*\d+\s*(?:คือ|=|:|–|—|-)\s*/i, ""));
    }).filter(Boolean);
    if (filled === 0 && parts.length >= n) return parts.slice(0, n);
    if (filled === 0 && n === 1 && parts.length >= 2) return parts.slice(0, 2);
    if (filled > 0) {
      for (i = 0; i < n; i++) if (!names[i]) names[i] = defaultQubitName(i);
      return names;
    }
    return null;
  }

