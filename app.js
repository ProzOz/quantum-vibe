  function persistWukongJob(pack) {
    if (!pack || !pack.wukongJobId) return;
    var jobId = String(pack.wukongJobId);
    var prev = loadWukongJob();
    var savedAt = Date.now();
    if (prev && String(prev.jobId) === jobId && prev.savedAt) savedAt = prev.savedAt;
    else if (state.wukongStarted) savedAt = state.wukongStarted;
    var status = pack.wukongStatus || "";
    if (!status) {
      if (pack.wukong && pack.wukong.ok) status = "finished";
      else if (pack.wukongWait) status = "running";
      else if (pack.wukongParseFail) status = "finished";
    }
    var curFp = circuitFingerprint(pack);
    var sameJob = !!(prev && String(prev.jobId) === jobId);
    var producerFp = "";
    if (sameJob && prev.circuitFingerprint) producerFp = String(prev.circuitFingerprint);
    if (!producerFp && isKnownBellJobId(jobId)) producerFp = bellDemoFingerprint();
    // Adopt on-screen fingerprint only when this pack produced the job (same circuit).
    if (!pack.wukongMismatch && pack.wukongCircuitFingerprint && curFp && pack.wukongCircuitFingerprint === curFp) {
      if (!producerFp || producerFp === curFp) producerFp = String(pack.wukongCircuitFingerprint);
    }
    if (isKnownBellJobId(jobId)) {
      var bellFp = bellDemoFingerprint();
      if (bellFp) producerFp = bellFp;
    }
    var rec = {
      jobId: jobId,
      consoleUrl: originConsoleUrl(jobId),
      rawResult: pack.wukongRaw != null ? pack.wukongRaw : null,
      status: status,
      savedAt: savedAt
    };
    rec.n = packN(pack);
    rec.shots = (pack.wukong && pack.wukong.shots) || WUKONG_SHOTS;
    rec.circuitFingerprint = producerFp;
    try {
      rec.title = resultTitle(pack) || "";
    } catch (e1) {
      rec.title = "";
    }
    if (pack.wukongDevice) rec.device = pack.wukongDevice;
    else if (pack.wukong && pack.wukong.device) rec.device = pack.wukong.device;
    var screenMismatch = !!pack.wukongMismatch || !!(producerFp && curFp && producerFp !== curFp);
    if (isKnownBellJobId(jobId) && screenCircuitKind(pack) !== "bell") screenMismatch = true;
    if (sameJob) {
      if (screenMismatch) {
        rec.circuitFingerprint = prev.circuitFingerprint || producerFp;
        if (isKnownBellJobId(jobId)) rec.circuitFingerprint = bellDemoFingerprint() || rec.circuitFingerprint;
        if (prev.title) rec.title = prev.title;
        if (prev.n) rec.n = prev.n;
        if (prev.shots) rec.shots = prev.shots;
        if (prev.device && !rec.device) rec.device = prev.device;
      } else if (prev.circuitFingerprint && !(pack.wukongCircuitFingerprint && pack.wukongCircuitFingerprint === curFp)) {
        rec.circuitFingerprint = prev.circuitFingerprint;
      }
      if (!rec.title && prev.title) rec.title = prev.title;
      if (rec.rawResult == null && prev.rawResult != null) rec.rawResult = prev.rawResult;
    }
    if (!pack.wukongMismatch && pack.wukong && pack.wukong.ok && pack.wukong.counts && !screenMismatch && wukongMatchesCircuit(pack, rec)) {
      rec.counts = pack.wukong.counts;
      rec.percents = pack.wukong.percents || null;
    } else if (sameJob && prev.counts) {
      rec.counts = prev.counts;
      rec.percents = prev.percents || null;
      if (prev.n) rec.n = prev.n;
      if (prev.shots) rec.shots = prev.shots;
    }
    if (pack.wukongParseFail) rec.parseFail = true;
    delete rec.origin_key;
    delete rec.originKey;
    delete rec.key;
    try {
      localStorage.setItem(WUKONG_JOB_KEY, JSON.stringify(rec));
    } catch (e) {}
  }

  function loadWukongJob() {
    try {
      var raw = localStorage.getItem(WUKONG_JOB_KEY);
      if (!raw) return null;
      var rec = JSON.parse(raw);
      if (!rec || typeof rec !== "object" || !rec.jobId) return null;
      delete rec.origin_key;
      delete rec.originKey;
      delete rec.key;
      return rec;
    } catch (e) {
      return null;
    }
  }

  function applySavedJobToPack(pack, rec) {
    if (!pack || !rec || !rec.jobId) return pack;
    pack.wukongJobId = String(rec.jobId);
    pack.wukongStatus = rec.status || "";
    pack.wukongDevice = rec.device || pack.wukongDevice || DEFAULT_DEVICE;
    if (rec.rawResult != null) pack.wukongRaw = rec.rawResult;
    pack.wukongError = null;
    pack.wukongParseFail = !!rec.parseFail;
    pack.wukongWait = false;
    pack.wukongStale = false;
    pack.wukong = null;
    pack.wukongMismatch = false;
    if (rec.circuitFingerprint) pack.wukongCircuitFingerprint = rec.circuitFingerprint;
    else if (isKnownBellJobId(rec.jobId)) pack.wukongCircuitFingerprint = bellDemoFingerprint();
    var match = wukongMatchesCircuit(pack, rec);
    if (!match) {
      if (rec.counts || rec.circuitFingerprint || rec.rawResult != null || isKnownBellJobId(rec.jobId)) {
        pack.wukongMismatch = true;
      }
      pack.wukong = null;
      return pack;
    }
    var n = rec.n || packN(pack);
    var shots = rec.shots || WUKONG_SHOTS;
    var parsed = null;
    if (rec.counts && typeof rec.counts === "object") {
      var keys = Object.keys(rec.counts);
      var has = keys.some(function (k) { return rec.counts[k] > 0; });
      if (has) {
        parsed = {
          counts: rec.counts,
          percents: rec.percents || null,
          shots: shots,
          n: n
        };
      }
    }
    if (!parsed && pack.wukongRaw != null && pack.wukongRaw !== "") {
      parsed = parseOriginResult(pack.wukongRaw, n, shots);
    }
    if (parsed) {
      pack.wukongParseFail = false;
      pack.wukongMismatch = false;
      pack.wukong = {
        ok: true,
        counts: parsed.counts,
        percents: parsed.percents,
        shots: parsed.shots || shots,
        n: parsed.n || n,
        device: pack.wukongDevice,
        job_id: pack.wukongJobId,
        noisy: true,
        real_qpu: true
      };
      pack.wukongStatus = rec.status || "finished";
      return pack;
    }
    var st = String(rec.status || "").toLowerCase();
    if (/received|queuing|running|processing|submitted/.test(st)) {
      pack.wukongWait = true;
      state.wukongStarted = rec.savedAt || state.wukongStarted || Date.now();
    } else if (st === "finished" || rec.parseFail) {
      pack.wukongParseFail = true;
    }
    return pack;
  }

