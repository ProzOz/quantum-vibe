  function resultNote(pack) {
    if (pack.source !== "kimi") {
      return pack.demo.mapNote[state.lang] + " " + pack.demo.explain[state.lang];
    }
    var lang = promptLang(pack.prompt);
    var raw = lang === "th"
      ? (pack.plan.explain_th || pack.plan.explain_en)
      : (pack.plan.explain_en || pack.plan.explain_th);
    raw = (raw || "").trim();
    var lines = raw.split(/\n+/).map(function (x) {
      return x.replace(/^\s*[-\d.]+[).\s]+/, "").trim();
    }).filter(Boolean);
    if (lines.length < 2 && pack.plan.mapping) {
      var m = String(pack.plan.mapping).trim();
      if (m && lines.indexOf(m) === -1) lines.unshift(m);
    }
    if (lines.length === 1) {
      lines = raw.split(/(?<=[.!?…])\s+/).map(function (x) { return x.trim(); }).filter(Boolean);
      if (pack.plan.mapping) {
        var mm = String(pack.plan.mapping).trim();
        if (mm && lines[0] !== mm) lines.unshift(mm);
      }
    }
    var body = [];
    for (var i = 0; i < lines.length; i++) {
      if (isDisclaimer(lines[i])) continue;
      body.push(lines[i]);
      if (body.length === 3) break;
    }
    body.push(jokeLine(lang));
    return body;
  }

