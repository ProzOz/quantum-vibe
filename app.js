  function runPrompt() {
    if (state.busy) return;
    var text = ($("prompt").value || "").trim();
    if (!text) {
      showPlanError(state.lang === "th" ? "พิมพ์ข้อความก่อนรัน" : "Type a prompt before Run");
      return;
    }
    state.busy = true;
    $("btnRun").disabled = true;
    stopWukongAll();
    startWaitTicker();
    var body = {
      prompt: text,
      base_url: state.baseUrl || DEFAULT_BASE,
      model: state.model || DEFAULT_MODEL,
      moonshot_key: state.moonshotKey || ""
    };
    postPlan(body, 0).then(function (json) {
      stopWaitTicker();
      applyPlan(json, text);
    }).catch(function (err) {
      stopWaitTicker();
      var msg = (err && err.message) ? err.message : String(err);
      if (!state.proxy.ok && isNetworkFail(err)) {
        msg = t("proxyMissing") + " — " + msg;
      }
      showPlanError(msg);
    }).then(function () {
      stopWaitTicker();
      state.busy = false;
      $("btnRun").disabled = false;
    });
  }

