  function originParsedFromPayload(pack, json, text) {
    saveWukongRaw(pack, json, text);
    var n = packN(pack);
    var shots = (json && json.shots) || (pack.wukong && pack.wukong.shots) || WUKONG_SHOTS;
    var parsed = null;
    if (pack.wukongRaw != null) parsed = parseOriginResult(pack.wukongRaw, n, shots);
    if (!parsed && json && json.counts) {
      var keys = Object.keys(json.counts);
      var has = keys.some(function (k) { return json.counts[k] > 0; });
      if (has) {
        parsed = {
          counts: json.counts,
          percents: json.percents || null,
          shots: shots,
          n: n
        };
        if (!parsed.percents) {
          parsed.percents = {};
          var tot = 0;
          keys.forEach(function (k) { tot += json.counts[k] || 0; });
          if (!tot) tot = 1;
          keys.forEach(function (k) { parsed.percents[k] = (json.counts[k] || 0) / tot * 100; });
        }
      }
    }
    if (!parsed && json) parsed = parseOriginResult(json, n, shots);
    if (!parsed && json && json.error) parsed = parseOriginResult(json.error, n, shots);
    if (!parsed && text) parsed = parseOriginResult(text, n, shots);
    return parsed;
  }

