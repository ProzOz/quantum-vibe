  function svgCircuit(circuit) {
    var n = circuit.n, gates = circuit.gates.filter(function (g) { return g.type !== "barrier"; });
    var colW = 56, rowH = 44, padX = 36, padY = 22;
    var cols = Math.max(gates.length, 1);
    var w = padX * 2 + cols * colW;
    var h = padY * 2 + n * rowH;
    var ns = "http://www.w3.org/2000/svg";
    var svg = document.createElementNS(ns, "svg");
    svg.setAttribute("viewBox", "0 0 " + w + " " + h);
    svg.setAttribute("class", "circuit-svg");
    svg.setAttribute("role", "img");
    svg.setAttribute("aria-label", "circuit");

    function yOf(q) { return padY + q * rowH + rowH / 2; }

    for (var q = 0; q < n; q++) {
      var line = document.createElementNS(ns, "line");
      line.setAttribute("x1", 8);
      line.setAttribute("x2", w - 8);
      line.setAttribute("y1", yOf(q));
      line.setAttribute("y2", yOf(q));
      line.setAttribute("stroke", "#5ce1e6");
      line.setAttribute("stroke-opacity", "0.45");
      line.setAttribute("stroke-width", "2");
      svg.appendChild(line);
      var lab = document.createElementNS(ns, "text");
      lab.setAttribute("x", 10);
      lab.setAttribute("y", yOf(q) - 10);
      lab.setAttribute("fill", "#93a0c2");
      lab.setAttribute("font-size", "11");
      lab.textContent = "q" + q;
      svg.appendChild(lab);
    }

    gates.forEach(function (g, i) {
      var x = padX + i * colW + colW / 2;
      if (g.type === "cx" || g.type === "cz" || g.type === "swap") {
        var y1 = yOf(g.a), y2 = yOf(g.b);
        var v = document.createElementNS(ns, "line");
        v.setAttribute("x1", x); v.setAttribute("x2", x);
        v.setAttribute("y1", y1); v.setAttribute("y2", y2);
        v.setAttribute("stroke", "#b388ff");
        v.setAttribute("stroke-width", "2");
        svg.appendChild(v);
        function dot(y, plus) {
          var c = document.createElementNS(ns, "circle");
          c.setAttribute("cx", x); c.setAttribute("cy", y); c.setAttribute("r", plus ? 9 : 5);
          c.setAttribute("fill", plus ? "none" : "#b388ff");
          c.setAttribute("stroke", "#b388ff");
          c.setAttribute("stroke-width", "2");
          svg.appendChild(c);
          if (plus) {
            var h = document.createElementNS(ns, "line");
            h.setAttribute("x1", x - 6); h.setAttribute("x2", x + 6); h.setAttribute("y1", y); h.setAttribute("y2", y);
            h.setAttribute("stroke", "#b388ff"); h.setAttribute("stroke-width", "2");
            svg.appendChild(h);
            var vv = document.createElementNS(ns, "line");
            vv.setAttribute("x1", x); vv.setAttribute("x2", x); vv.setAttribute("y1", y - 6); vv.setAttribute("y2", y + 6);
            vv.setAttribute("stroke", "#b388ff"); vv.setAttribute("stroke-width", "2");
            svg.appendChild(vv);
          }
        }
        if (g.type === "cx") { dot(y1, false); dot(y2, true); }
        else if (g.type === "cz") { dot(y1, false); dot(y2, false); }
        else { boxAt(x, yOf(g.a), "×"); boxAt(x, yOf(g.b), "×"); }
      } else {
        var label = g.type.toUpperCase();
        if (g.theta != null) label = label + "°";
        boxAt(x, yOf(g.q), label);
      }
    });

    function boxAt(x, y, label) {
      var r = document.createElementNS(ns, "rect");
      r.setAttribute("x", x - 16); r.setAttribute("y", y - 14);
      r.setAttribute("width", 32); r.setAttribute("height", 28); r.setAttribute("rx", 6);
      r.setAttribute("fill", "#141c33"); r.setAttribute("stroke", "#5ce1e6");
      svg.appendChild(r);
      var tx = document.createElementNS(ns, "text");
      tx.setAttribute("x", x); tx.setAttribute("y", y + 4);
      tx.setAttribute("text-anchor", "middle");
      tx.setAttribute("fill", "#e8eefc");
      tx.setAttribute("font-size", label.length > 3 ? "9" : "11");
      tx.setAttribute("font-family", "ui-monospace, monospace");
      tx.textContent = label;
      svg.appendChild(tx);
    }
    return svg;
  }

