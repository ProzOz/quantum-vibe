  function cleanQubitName(s) {
    s = String(s || "").trim();
    s = s.replace(/^[\s"'“”‘’]+|[.。,;:]+$/g, "").trim();
    s = s.replace(/\s+/g, " ");
    s = s.replace(/^(is|are|was|the)\s+/i, "").trim();
    if (s.length > 32) s = s.slice(0, 32).replace(/\s+\S*$/, "");
    if (/^(q(?:ubit)?\s*\d+|ควิบิต\s*\d+)/i.test(s)) return "";
    if (/qubit|ควิบิต/i.test(s)) return "";
    if (s.length < 1) return "";
    return s;
  }

